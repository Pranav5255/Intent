#!/usr/bin/env bash
# Write the Homebrew cask for the desktop app from built disk images.
#   packaging/homebrew/make-cask.sh <version> <arm64.dmg> [<x86_64.dmg>] > Casks/intent-app.rb
# A release publishes the images as Intent_<version>_aarch64.dmg and Intent_<version>_x64.dmg.
# Set CASK_URL to use one local image instead (CI installs the cask from its own build).
# Set FORMULA to depend on a formula in another tap (default pranav5255/intent/intent).
set -euo pipefail

version=${1:?version}
arm=${2:?arm64 disk image}
intel=${3:-}
formula=${FORMULA:-pranav5255/intent/intent}
sha() { shasum -a 256 "$1" | cut -d' ' -f1; }

echo '# Generated by packaging/homebrew/make-cask.sh. The app needs the intent formula.'
echo 'cask "intent-app" do'
arch_dep=
if [[ -n ${CASK_URL:-} ]]; then
  printf '  version "%s"\n  sha256 "%s"\n\n  url "%s"\n' "$version" "$(sha "$arm")" "$CASK_URL"
elif [[ -n $intel ]]; then
  printf '  arch arm: "aarch64", intel: "x64"\n\n  version "%s"\n' "$version"
  printf '  sha256 arm:   "%s",\n         intel: "%s"\n\n' "$(sha "$arm")" "$(sha "$intel")"
  echo '  url "https://github.com/Pranav5255/Intent/releases/download/v#{version}/Intent_#{version}_#{arch}.dmg"'
else
  printf '  version "%s"\n  sha256 "%s"\n\n' "$version" "$(sha "$arm")"
  echo '  url "https://github.com/Pranav5255/Intent/releases/download/v#{version}/Intent_#{version}_aarch64.dmg"'
  arch_dep=$'  depends_on arch: :arm64\n'
fi
cat <<RUBY
  name "Intent"
  desc "Remembers what you were working on and reopens it"
  homepage "https://github.com/Pranav5255/Intent"

${arch_dep}  depends_on formula: "$formula"
  depends_on :macos

  app "Intent.app"

  zap trash: [
    "~/Library/Application Support/io.github.pranav5255.Intent",
    "~/Library/Caches/io.github.pranav5255.Intent",
    "~/Library/LaunchAgents/io.github.pranav5255.intentd.plist",
    "~/Library/Logs/Intent",
    "~/Library/WebKit/io.github.pranav5255.Intent",
  ]

  caveats <<~EOS
    Start the daemon at login with:
      intentctl enable
    Open the palette from anywhere with Option-Space.
  EOS
end
RUBY
